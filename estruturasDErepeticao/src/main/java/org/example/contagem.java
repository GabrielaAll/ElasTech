package org.example;

public class contagem {
    public static void main(String[] args) {

        //2 - Mostre a contagem regressiva de 10 até 1 e depois a palavra "Fim!".

        for (int i = 10; i >= 1; i--){
            System.out.println(i);
        }
        System.out.println("Fim!");
    }
}
